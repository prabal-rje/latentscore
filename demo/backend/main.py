# ─── Active Sessions ─────────────────────────────────────────────────────────

class ActiveSession:
    def __init__(self, session_id: str, config: MusicConfig, vibe: str):
        self.session_id = session_id
        self.config = config
        self.vibe = vibe
        self.active_ws_id: str | None = None

    def update_config(self, updates: dict[str, Any]) -> MusicConfig:
        current = self.config.model_dump()
        for key, value in updates.items():
            if key in current:
                if key == "density":
                    value = int(value)
                current[key] = value
        self.config = MusicConfig.model_validate(current)
        return self.config


