# ─── CLAP Best-of-N Selection ─────────────────────────────────────────────────


def _cosine_sim(a: np.ndarray, b: np.ndarray) -> float:
    """Cosine similarity between two vectors (or batches)."""
    a = a.flatten()
    b = b.flatten()
    return float(np.dot(a, b) / (np.linalg.norm(a) * np.linalg.norm(b) + 1e-8))


class CandidateConfig(BaseModel):
    config: dict[str, Any]
    justification: str = ""
    title: str | None = None
    palette: list[str] | None = None


class SelectBestRequest(BaseModel):
    vibe: str
    candidates: list[CandidateConfig]


@app.post("/api/select-best-config", response_model=GenerateResponse)
async def select_best_config(req: SelectBestRequest):
    """Render audio for each candidate config, CLAP-score against vibe, return best."""
    if not clap_model:
        raise ValueError("CLAP model not loaded")
    if not req.candidates:
        raise ValueError("No candidates provided")

    # Validate all configs — coerce LLM enum labels to numeric values
    configs: list[MusicConfig] = []
    for c in req.candidates:
        configs.append(_coerce_config(c.config))

    # Render 30s audio for each candidate in parallel
    loop = asyncio.get_running_loop()
    render_tasks = [
        loop.run_in_executor(synth_pool, _render_audio_sync, cfg, 30.0)
        for cfg in configs
    ]
    wav_bytes_list = await asyncio.gather(*render_tasks)

    # Write temp WAV files for CLAP (it needs file paths)
    tmp_paths: list[str] = []
    try:
        for i, wav_bytes in enumerate(wav_bytes_list):
            tmp = tempfile.NamedTemporaryFile(suffix=".wav", delete=False)
            tmp.write(wav_bytes)
            tmp.close()
            tmp_paths.append(tmp.name)

        # CLAP scoring
        text_embed = clap_model.get_text_embedding([req.vibe])
        audio_embeds = clap_model.get_audio_embedding_from_filelist(tmp_paths)

        scores = [_cosine_sim(audio_embeds[i], text_embed[0]) for i in range(len(tmp_paths))]
        best_idx = int(np.argmax(scores))

        logger.info(
            f"CLAP scores for '{req.vibe[:40]}': "
            + ", ".join(f"[{i}]={s:.4f}" for i, s in enumerate(scores))
            + f" → winner: [{best_idx}]"
        )
    finally:
        import os
        for p in tmp_paths:
            try:
                os.unlink(p)
            except OSError:
                pass

    # Create session for the winning candidate
    winner = req.candidates[best_idx]
    winner_config = configs[best_idx]
    session_id = str(uuid.uuid4())[:8]
    session = ActiveSession(session_id, winner_config, req.vibe)
    sessions[session_id] = session

    title = winner.title or generate_title(req.vibe, winner_config)
    palette = winner.palette if winner.palette and len(winner.palette) == 5 else generate_palette(winner_config, req.vibe)

    return GenerateResponse(
        session_id=session_id,
        title=title,
        justification=winner.justification or generate_justification(req.vibe, winner_config),
        palette=palette,
        config=winner_config.model_dump(),
    )


# ─── DSP Rendering ───────────────────────────────────────────────────────────


def _float_array_to_wav(
    samples: np.ndarray, sample_rate: int = ls.SAMPLE_RATE
) -> bytes:
    """Encode float32 numpy samples → WAV bytes."""
    samples = np.clip(samples, -1.0, 1.0)
    buf = io.BytesIO()
    n_samples = len(samples)
    data_size = n_samples * 2
    buf.write(b"RIFF")
    buf.write(struct.pack("<I", 36 + data_size))
    buf.write(b"WAVEfmt ")
    buf.write(struct.pack("<IHHIIHH", 16, 1, 1, sample_rate, sample_rate * 2, 2, 16))
    buf.write(b"data")
    buf.write(struct.pack("<I", data_size))
    buf.write((samples * 32767).astype(np.int16).tobytes())
    return buf.getvalue()


def _render_audio_sync(config: MusicConfig, duration: float = 60.0) -> bytes:
    """Render full audio → WAV bytes. Runs in a subprocess."""
    internal = config.to_internal()
    samples = assemble(internal, duration=duration)
    return _float_array_to_wav(np.asarray(samples, dtype=np.float32))


# ─── Full Render Endpoint ───────────────────────────────────────────────────


@app.get("/api/render/{session_id}")
async def render_audio(session_id: str, duration: float = 60.0):
    """Render full audio for a session, return WAV bytes."""
    session = sessions.get(session_id)
    if not session:
        return Response(content="Session not found", status_code=404)

    duration = min(duration, 300.0)  # cap at 5 minutes
    loop = asyncio.get_running_loop()
    wav_bytes = await loop.run_in_executor(
        synth_pool, _render_audio_sync, session.config, duration
    )
    return Response(content=wav_bytes, media_type="audio/wav")


# ─── WebSocket Live Streaming (phase-continuous via ls.live) ─────────────────


@app.websocket("/ws/stream/{session_id}")
async def websocket_stream(websocket: WebSocket, session_id: str):
    await websocket.accept()

    session = sessions.get(session_id)
    if not session:
        await websocket.send_json({"type": "error", "message": "Session not found"})
        await websocket.close()
        return

    ws_id = str(uuid.uuid4())[:8]
    session.active_ws_id = ws_id
    chunk_duration = 2.0

    logger.info(f"Starting live stream for session {session_id} (ws={ws_id})")

    stopped = False

    async def receive_messages():
        nonlocal stopped
        try:
            while not stopped:
                msg = await websocket.receive_json()
                if msg.get("type") == "stop":
                    stopped = True
                    break
        except (WebSocketDisconnect, Exception):
            stopped = True

    recv_task = asyncio.create_task(receive_messages())
    stream = ls.live(session.config, chunk_seconds=chunk_duration)

    try:
        async for chunk in stream.achunks(seconds=600):
            if stopped or session.active_ws_id != ws_id:
                break

            wav_bytes = _float_array_to_wav(chunk)
            b64 = base64.b64encode(wav_bytes).decode("ascii")
            await websocket.send_json({
                "type": "audio_chunk",
                "data": b64,
                "duration": chunk_duration,
            })

    except WebSocketDisconnect:
        logger.info(f"Client disconnected from session {session_id} (ws={ws_id})")
    except Exception as e:
        logger.error(f"Stream error: {e}")
        try:
            await websocket.send_json({"type": "error", "message": str(e)})
        except Exception:
            pass
    finally:
        stream.close()
        recv_task.cancel()
        if session.active_ws_id == ws_id:
            session.active_ws_id = None
        logger.info(f"Live stream ended for session {session_id} (ws={ws_id})")


