def _coerce_config(raw: dict[str, Any]) -> MusicConfig:
    """Convert LLM config (may have enum labels) into MusicConfig (needs floats).

    Robust against LLMs inventing values — strips any field that fails validation.
    """
    data = dict(raw)
    for field, converter in _LABEL_CONVERTERS.items():
        if field in data and isinstance(data[field], str):
            try:
                data[field] = converter(data[field])
            except Exception:
                del data[field]  # let MusicConfig use its default
    # Clamp integer fields to valid ranges
    if "density" in data:
        try:
            data["density"] = max(2, min(6, int(data["density"])))
        except (ValueError, TypeError):
            del data["density"]
    if "phrase_len_bars" in data:
        try:
            v = int(data["phrase_len_bars"])
            data["phrase_len_bars"] = min((2, 4, 8), key=lambda x: abs(x - v))
        except (ValueError, TypeError):
            del data["phrase_len_bars"]
    schema_fields = set(MusicConfig.model_fields.keys())
    filtered = {k: v for k, v in data.items() if k in schema_fields}
    # Try validation; on failure, strip offending fields one at a time
    while True:
        try:
            return MusicConfig.model_validate(filtered)
        except _ValidationError as exc:
            bad_fields = {e["loc"][0] for e in exc.errors() if e.get("loc")}
            if not bad_fields:
                return MusicConfig()  # give up, use all defaults
            for f in bad_fields:
                filtered.pop(f, None)
                logger.warning("Stripped invalid LLM field %s", f)


