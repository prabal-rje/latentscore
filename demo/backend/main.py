# ─── Enriched embedding model ────────────────────────────────────────────────
# Subclasses FastEmbeddingModel to also return the title and palettes stored
# alongside each config in the embed map JSONL (generated by LLMs during
# training data creation).

class _VibeResult:
    """Result from vibe_to_config: config + optional metadata from the embed map."""
    __slots__ = ("config", "title", "palettes")

    def __init__(
        self,
        config: MusicConfig,
        title: str | None = None,
        palettes: list[dict[str, Any]] | None = None,
    ):
        self.config = config
        self.title = title
        self.palettes = palettes


class EnrichedFastModel(FastEmbeddingModel):
    """FastEmbeddingModel that also captures title and palettes from the embed map."""

    def __init__(self) -> None:
        super().__init__()
        self._row_titles: list[str | None] = []
        self._row_palettes: list[list[dict[str, Any]] | None] = []

    @functools.lru_cache(maxsize=1)
    def _embed_map_examples(self) -> tuple[tuple[ExampleConfig, ...], np.ndarray | None]:
        """Override to also capture title and palettes per row."""
        from latentscore.models import _fast_track_examples

        map_path = self._resolve_embed_map_path()
        if map_path is None or not map_path.exists():
            fallback = _fast_track_examples()
            self._row_titles = [None] * len(fallback)
            self._row_palettes = [None] * len(fallback)
            return fallback, None

        examples: list[ExampleConfig] = []
        embeddings: list[list[float]] = []
        titles: list[str | None] = []
        palettes: list[list[dict[str, Any]] | None] = []

        try:
            with map_path.open("r", encoding="utf-8") as handle:
                for line in handle:
                    if not line.strip():
                        continue
                    try:
                        row = _json.loads(line)
                    except _json.JSONDecodeError:
                        continue
                    if self._exclude_splits and row.get("split") in self._exclude_splits:
                        continue
                    vibe = row.get("vibe_original") or row.get("vibe") or row.get("vibe_noisy")
                    config_data = row.get("config")
                    if not vibe or not isinstance(config_data, dict):
                        continue
                    try:
                        prompt_config = MusicConfigPrompt.model_validate(config_data)
                        music_config = prompt_config.to_config()
                    except _ValidationError:
                        try:
                            music_config = MusicConfig.model_validate(config_data)
                        except _ValidationError:
                            continue
                    examples.append(ExampleConfig(vibe=str(vibe), config=music_config))
                    titles.append(row.get("title"))
                    palettes.append(row.get("palettes"))
                    embed: object = row.get("embedding")
                    if isinstance(embed, list):
                        embeddings.append([float(v) for v in cast(list[Any], embed)])
        except OSError as exc:
            logger.warning("Failed reading embedding map: %s", exc, exc_info=True)
            fallback = _fast_track_examples()
            self._row_titles = [None] * len(fallback)
            self._row_palettes = [None] * len(fallback)
            return fallback, None

        if not examples:
            fallback = _fast_track_examples()
            self._row_titles = [None] * len(fallback)
            self._row_palettes = [None] * len(fallback)
            return fallback, None

        self._row_titles = titles
        self._row_palettes = palettes

        matrix: np.ndarray | None = None
        if len(embeddings) == len(examples):
            mat = np.asarray(embeddings, dtype=np.float32)
            norms = np.linalg.norm(mat, axis=1, keepdims=True)
            norms[norms == 0] = 1.0
            matrix = mat / norms
        return tuple(examples), matrix

    async def generate_with_meta(self, vibe: str) -> _VibeResult:
        """Generate config + title/palettes in one thread-safe call."""
        try:
            return await asyncio.to_thread(self._select_with_meta, vibe)
        except Exception as exc:
            logger.warning("Fast model fallback: %s", exc, exc_info=True)
            return _VibeResult(_heuristic_config(vibe))

    def _select_with_meta(self, vibe: str) -> _VibeResult:
        encoder = self._load_encoder()
        example_matrix = self._example_matrix()
        query = encoder.encode([vibe], normalize_embeddings=True)
        query_vec = np.asarray(query, dtype=np.float32)[0]
        scores = example_matrix @ query_vec
        best_idx = int(np.argmax(scores))
        config = self._examples()[best_idx].config
        title = self._row_titles[best_idx] if best_idx < len(self._row_titles) else None
        palettes = self._row_palettes[best_idx] if best_idx < len(self._row_palettes) else None
        return _VibeResult(config, title, palettes)


def _palette_from_embed(palettes_data: list[dict[str, Any]]) -> list[str] | None:
    """Convert embed map palette data to 5 hex strings for the frontend.

    The embed map stores 3 palettes of 5 weighted colors each.  We take the
    first palette and reorder by luminance: darkest → position [3] (background),
    brightest → position [4] (accent), rest → [0-2].
    """
    if not palettes_data:
        return None
    colors = palettes_data[0].get("colors", [])
    if len(colors) != 5:
        return None
    hexes = [c.get("hex", "#000000") for c in colors]

    def lum(h: str) -> float:
        try:
            r, g, b = int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16)
        except (ValueError, IndexError):
            return 0
        return 0.299 * r + 0.587 * g + 0.114 * b

    by_lum = sorted(range(5), key=lambda i: lum(hexes[i]))
    bg_idx = by_lum[0]       # darkest → background
    accent_idx = by_lum[-1]  # brightest → accent
    mid = [i for i in range(5) if i != bg_idx and i != accent_idx]
    return [hexes[mid[0]], hexes[mid[1]], hexes[mid[2]], hexes[bg_idx], hexes[accent_idx]]


